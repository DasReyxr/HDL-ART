module Display7 (
    input  logic [3:0] Sw,
    output logic [6:0] Disp
);

// G to A: MSB (G) = bit 6, LSB (A) = bit 0
assign Disp = 
            (Sw == 4'b1111) ? 7'b0111111 :
            (Sw == 4'b1110) ? 7'b0000110 :
            (Sw == 4'b1101) ? 7'b1011011 :
            (Sw == 4'b1100) ? 7'b1001111 :
            (Sw == 4'b1011) ? 7'b1100110 :
            (Sw == 4'b1010) ? 7'b1101101 :
            (Sw == 4'b1001) ? 7'b1111101 :
            (Sw == 4'b1000) ? 7'b0000111 :
            (Sw == 4'b0111) ? 7'b1111111 :
            (Sw == 4'b0110) ? 7'b1101111 :
                            7'b0000000;

endmodule
